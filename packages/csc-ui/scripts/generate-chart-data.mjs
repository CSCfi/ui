// Generate src/theme/chart-data.ts — the chart tokens (ADR-0030) published as
// importable data (ADR-0040): the twelve series slots and the chart anatomy
// roles per theme mode, as `oklch()` strings plus a `#rrggbb` twin.
//
// Source of truth is tokens/semantic/{light,dark}.json (the same files
// style-dictionary turns into --c-chart-* in tokens.css), and the oklch()
// strings come from the same cssColor() the CSS emitter uses (ADR-0041), so
// the CSS variable and the exported value are the same string.
// `scripts/check-chart-parity.mjs` (`pnpm run lint:chart`) fails when the
// committed module is stale.
//
// Usage:  node scripts/generate-chart-data.mjs          (writes the module)
//         node scripts/generate-chart-data.mjs --check  (prints, does not write)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { cssColor } from '../src/theme/ramp.js';

const dir = path.dirname(fileURLToPath(import.meta.url));

const read = (p) => JSON.parse(fs.readFileSync(path.resolve(dir, p), 'utf8'));

export const OUT = path.resolve(dir, '../src/theme/chart-data.ts');

const SLOT_COUNT = 12;

const ANATOMY = ['surface', 'grid', 'axis'];

const MODES = ['light', 'dark'];

export function render() {
  const step = paletteLookup();

  const modes = Object.fromEntries(
    MODES.map((m) => [
      m,
      resolveMode(read(`../tokens/semantic/${m}.json`), step),
    ]),
  );

  const q = (s) => `'${s}'`;

  const slotsOf = (mode, fmt, indent) =>
    `[\n${mode.slots.map((v) => `${indent}  ${q(fmt(v))},`).join('\n')}\n${indent}]`;

  const anatomyOf = (mode, fmt, indent) =>
    `{\n${ANATOMY.map((r) => `${indent}  ${r}: ${q(fmt(mode.anatomy[r]))},`).join('\n')}\n${indent}}`;

  const record = (fmt, pick) =>
    `{\n${MODES.map((m) => `  ${m}: ${pick(modes[m], fmt, '  ')},`).join('\n')}\n}`;

  const hex = (h) => h;

  const slotTuple = `\n${Array(SLOT_COUNT).fill('  string,').join('\n')}\n`;

  return `/* eslint-disable */
/**
 * GENERATED by scripts/generate-chart-data.mjs from
 * tokens/semantic/{light,dark}.json — do not edit.
 * Regenerate with \`pnpm run chart:generate\`; \`pnpm run lint:chart\` fails
 * the build when this file is stale.
 *
 * The chart tokens (ADR-0030) as importable data (ADR-0040): the twelve
 * series slots and the chart anatomy roles per theme mode. Values are the
 * frozen, validated set — they never follow a consumer's \`--c-chart-*\`
 * overrides. Pair with \`themeMode()\` to pick the mode on screen.
 */

import type { ThemeMode } from './themeMode';

/** The twelve series slots in slot order (\`chart-1\` … \`chart-12\`). */
export type ChartSlots = readonly [${slotTuple}];

/** The chart anatomy roles: plot background, gridlines/axes, tick labels. */
export interface ChartAnatomy {
  readonly surface: string;
  readonly grid: string;
  readonly axis: string;
}

/**
 * Series slots per theme mode as \`oklch(L C H)\` strings — the palette's own
 * colour space, ready for CSS, SVG and canvas \`fillStyle\`, and the exact
 * string the \`--c-chart-*\` variable holds (ADR-0041). Each round-trips to
 * the \`#rrggbb\` in \`chartSlotsHex\`.
 */
export const chartSlots: Readonly<Record<ThemeMode, ChartSlots>> = ${record(cssColor, slotsOf)};

/**
 * Series slots per theme mode as \`#rrggbb\` — for chart libraries that do
 * their own colour maths in sRGB (ECharts, Chart.js) and cannot parse
 * \`oklch()\`. Same colours and order as \`chartSlots\`.
 */
export const chartSlotsHex: Readonly<Record<ThemeMode, ChartSlots>> = ${record(hex, slotsOf)};

/** Chart anatomy roles per theme mode as \`oklch(L C H)\` strings. */
export const chartAnatomy: Readonly<Record<ThemeMode, ChartAnatomy>> = ${record(cssColor, anatomyOf)};

/** Chart anatomy roles per theme mode as \`#rrggbb\`. */
export const chartAnatomyHex: Readonly<Record<ThemeMode, ChartAnatomy>> = ${record(hex, anatomyOf)};
`;
}

/** Palette step key ("slate-800", "white") or literal hex → 6-digit hex. */
function paletteLookup() {
  const base = read('../tokens/theme/base.json');

  const palette = {};

  (function walk(o, p) {
    if (o && typeof o === 'object') {
      if (typeof o.value === 'string') palette[p] = o.value;
      else for (const k in o) walk(o[k], p ? `${p}-${k}` : k);
    }
  })(base.theme, '');

  return (key) => {
    const v = key.startsWith('#') ? key : palette[key];

    if (!v || !/^#[0-9a-f]{6}(ff)?$/i.test(v)) {
      throw new Error(`chart-data: cannot resolve "${key}" to an opaque hex`);
    }

    return v.slice(0, 7).toLowerCase();
  };
}

/** Resolve one mode's semantic map to { slots: hex[12], anatomy: {…} }. */
function resolveMode(map, step) {
  const pick = (key) => {
    if (!(key in map)) throw new Error(`chart-data: ${key} missing`);

    return step(map[key]);
  };

  return {
    anatomy: Object.fromEntries(
      ANATOMY.map((role) => [role, pick(`chart-${role}`)]),
    ),
    slots: Array.from({ length: SLOT_COUNT }, (_, i) => pick(`chart-${i + 1}`)),
  };
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const out = render();

  if (process.argv.includes('--check')) {
    process.stdout.write(out);
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
  }
}
